import Foundation

/// Something you copied.
struct Clip: Identifiable, Equatable {
    let id: UUID
    let text: String
    let at: Date

    /// One line of it, for the list.
    var preview: String {
        let line = text.split(whereSeparator: { $0.isNewline }).first { $0.contains { !$0.isWhitespace } }.map { String($0) } ?? ""
        return String(line.trimmingCharacters(in: .whitespaces).prefix(160))
    }

    /// How many lines it has (blank lines at the end don't count).
    var lineCount: Int {
        var lines = text.split(omittingEmptySubsequences: false, whereSeparator: { $0.isNewline })
        while let last = lines.last, last.allSatisfy({ $0.isWhitespace }), lines.count > 1 {
            lines.removeLast()
        }
        return lines.count
    }
}

/// The last things you copied, newest first. Held in memory only: never written to disk,
/// never sent anywhere, and gone when the app quits.
struct ClipList: Equatable {
    static let limit = 30
    /// Longer than this isn't kept (a whole document, say).
    static let longest = 20_000

    private(set) var clips: [Clip] = []

    /// Remembers something copied. The same text again moves to the top. Returns whether
    /// the list changed.
    @discardableResult
    mutating func add(_ text: String, at date: Date = Date()) -> Bool {
        guard text.contains(where: { !$0.isWhitespace }), text.count <= ClipList.longest else { return false }
        if clips.first?.text == text { return false }
        clips.removeAll { $0.text == text }
        clips.insert(Clip(id: UUID(), text: text, at: date), at: 0)
        if clips.count > ClipList.limit {
            clips.removeLast(clips.count - ClipList.limit)
        }
        return true
    }

    mutating func remove(_ id: UUID) {
        clips.removeAll { $0.id == id }
    }

    mutating func clear() {
        clips = []
    }

    /// Marks on a copy that say "don't keep this": password managers put them on passwords,
    /// and apps put them on things copied only for a moment.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    /// Whether a copy carries one of those marks.
    static func isPrivate(types: [String]) -> Bool {
        types.contains { privateTypes.contains($0) }
    }
}
